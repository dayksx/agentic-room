const checkPortAvailable = (port: number): Promise<boolean> => {
    return new Promise((resolve) => {
        const server = net.createServer();

        server.once("error", (err: NodeJS.ErrnoException) => {
            if (err.code === "EADDRINUSE") {
                resolve(false);
            }
        });

        server.once("listening", () => {
            server.close();
            resolve(true);
        });

        server.listen(port);
    });
};



const startAgents = async () => {
    let serverPort = Number.parseInt(settings.SERVER_PORT || "3000");

    try {

        let db: IDatabaseAdapter & IDatabaseCacheAdapter;
        const token = getTokenForProvider(wagmAICharacter.modelProvider, wagmAICharacter);
        const dataDir = path.join(__dirname, "../data");

        if (!fs.existsSync(dataDir)) {
            fs.mkdirSync(dataDir, { recursive: true });
        }

        db = initializeDatabase(dataDir) as IDatabaseAdapter &
            IDatabaseCacheAdapter;

        await db.init();

        const cache = initializeCache(
            dataDir,
            defaultCharacter,
        );
        console.log("cache", cache);
        const runtime = new AgentRuntime({
            databaseAdapter: db,
            token,
            modelProvider: wagmAICharacter.modelProvider,
            evaluators: [],
            character: wagmAICharacter,
            // character.plugins are handled when clients are added
            plugins: [rewardsPlugin, twitterPlugin].flat().filter(Boolean),
            providers: [],
            managers: [],
            cacheManager: cache,
            fetch: logFetch,
        });

        // start services/plugins/process knowledge
     //   await runtime.initialize();

        // start assigned clients
      //  runtime.clients = await initializeClients(wagmAICharacter, runtime);

        // add to container

        // report to console
        elizaLogger.debug(`Started ${wagmAICharacter.name} as ${runtime.agentId}`);
        
    } catch (error) {
        elizaLogger.error("Error starting agents:", error);
    }

    // Find available port
    while (!(await checkPortAvailable(serverPort))) {
        elizaLogger.warn(
            `Port ${serverPort} is in use, trying ${serverPort + 1}`
        );
        serverPort++;
    }


    if (serverPort !== Number.parseInt(settings.SERVER_PORT || "3000")) {
        elizaLogger.log(`Server started on alternate port ${serverPort}`);
    }
};

startAgents().catch((error) => {
    elizaLogger.error("Unhandled error in startAgents:", error);
    process.exit(1);
});
